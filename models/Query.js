import mongoose from 'mongoose';

const QuerySchema = new mongoose.Schema({
  userId: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'User',
    index: true,
    default: null,
  },
  queryId: {
    type: String,
    unique: true,
    sparse: true,
    default: null
  },
  name: {
    type: String,
    required: [true, 'Full name is required'],
    trim: true
  },
  mobile: {
    type: String,
    required: [true, 'Mobile number is required'],
    match: [/^[6-9]\d{9}$/, 'Please provide a valid 10-digit mobile number']
  },
  ward: {
    type: Number,
    required: [true, 'Ward number is required'],
    min: [1, 'Ward number must be at least 1'],
    max: [20, 'Ward number cannot exceed 20']
  },
  village: { type: String, trim: true, default: '' },
  category: {
    type: String,
    enum: [
      'Water',
      'Road',
      'Electricity',
      'Health/PHC',
      'Pension',
      'Ration',
      'Certificates',
      'Drainage',
      'Street Light',
      'Anganwadi',
      'School',
      'Others'
    ],
    required: [true, 'Category is required']
  },
  subject: {
    type: String,
    required: [true, 'Subject is required'],
    maxlength: [100, 'Subject cannot exceed 100 characters'],
    trim: true
  },
  description: {
    type: String,
    required: [true, 'Description is required'],
    trim: true
  },
  address: {
    type: String,
    default: ''
  },
  photo: {
    type: String,
    default: null
  },
  attachments: [{
    fileName: String,
    fileUrl: String,
    mimeType: String,
    uploadedAt: { type: Date, default: Date.now },
  }],
  status: {
    type: String,
    enum: ['Pending', 'In Review', 'In Progress', 'Need More Information', 'Resolved', 'Rejected', 'Closed', 'New'],
    default: 'Pending'
  },
  priority: {
    type: String,
    enum: ['High', 'Medium', 'Low'],
    default: 'Medium'
  },
  assignedTo: {
    type: String,
    enum: ['Ward Member-1', 'Ward Member-2', 'Ward Member-3', 'Ward Member-4', 'Ward Member-5', 'Ward Member-6', 'Ward Member-7', 'Ward Member-8', 'Ward Member-9', 'Ward Member-10', 'Secretary', 'JE', 'Pradhan'],
    default: null
  },
  adminRemarks: {
    type: String,
    default: ''
  },
  internalNotes: {
    type: String,
    default: ''
  },
  resolutionPhoto: {
    type: String,
    default: null
  },
  escalate: {
    type: Boolean,
    default: false
  },
  acknowledgedAt: {
    type: Date,
    default: null
  },
  resolvedAt: {
    type: Date,
    default: null
  },
  resolution: {
    message: { type: String, default: '' },
    department: { type: String, default: '' },
    documentUrl: { type: String, default: null },
    resolvedBy: { type: mongoose.Schema.Types.ObjectId, ref: 'User', default: null },
  },
  auditLog: [
    {
      action: String,
      changedBy: String,
      changedAt: {
        type: Date,
        default: Date.now
      },
      from: mongoose.Schema.Types.Mixed,
      to: mongoose.Schema.Types.Mixed
    }
  ]
}, {
  timestamps: true
});

QuerySchema.index({ userId: 1, createdAt: -1 });
QuerySchema.index({ status: 1, priority: 1, village: 1, ward: 1, createdAt: -1 });

