function getTranslation(text, language) {
  return language === "hi" ? HINDI[text] : ENGLISH[text];
}

function localizeToast(value, language) {
  if (typeof value === "string") {
    const text = value.replace(/\s+/g, " ").trim();
    return getTranslation(text, language) || value;
  }

  if (Array.isArray(value)) {
    return value.map((item) => localizeToast(item, language));
  }

  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value).map(([key, item]) => [key, localizeToast(item, language)])
    );
  }

  return value;
}

function localizeNode(node, language) {
  if (typeof node === "string") {
    const leading = node.match(/^\s*/)?.[0] ?? "";
    const trailing = node.match(/\s*$/)?.[0] ?? "";
    const content = node.trim().replace(/\s+/g, " ");
    const translated = getTranslation(content, language);
    return translated
      ? `${leading}${translated}${trailing}`
      : node;
  }

  if (Array.isArray(node)) {
    return node.map((child) => localizeNode(child, language));
  }

  if (!isValidElement(node) || node.props?.translate === "no") {
    return node;
  }

  const props = {};
  if (node.props.toasts) {
    props.toasts = localizeToast(node.props.toasts, language);
  }
  for (const name of ["alt", "aria-label", "placeholder", "title"]) {
    const value = node.props[name];
    if (typeof value === "string") {
      const translated = getTranslation(value, language);
      if (translated) props[name] = translated;
    }
  }

  if (node.props.dangerouslySetInnerHTML || node.type === "input" || node.type === "textarea") {
    return cloneElement(node, props);
  }

  return cloneElement(node, props, localizeNode(node.props.children, language));
}

export function withAdminTranslations(Page) {
  function TranslatedAdminPage(props) {
    const { language } = useLanguage();
    // The wrapped page is called unconditionally so its existing hooks remain stable.
    return localizeNode(Page(props), language);
  }

  TranslatedAdminPage.displayName = `withAdminTranslations(${Page.displayName || Page.name || "Page"})`;
  return TranslatedAdminPage;
}
